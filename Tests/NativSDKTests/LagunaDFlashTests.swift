@testable import NativSDK

final class LagunaDFlashTests: XCTestCase {
    private func fixture() throws -> URL {
        try XCTUnwrap(
            Bundle.module.url(
                forResource: "laguna-dflash", withExtension: nil, subdirectory: "Fixtures"))
    }
    private func data(_ name: String) throws -> Data {
        try Data(contentsOf: fixture().appendingPathComponent(name + ".json"))
    }
    private func target(moe: Bool = false) throws -> Laguna {
        var root = try JSONSerialization.jsonObject(with: data("target-config")) as! [String: Any]
        if moe {
            root["num_experts"] = 4
            root["num_experts_per_tok"] = 2
            root["moe_intermediate_size"] = 8
            root["shared_expert_intermediate_size"] = 8
            root["moe_routed_scaling_factor"] = 2.5
        }
        let config = try JSONDecoder().decode(
            LagunaConfiguration.self, from: JSONSerialization.data(withJSONObject: root))
        let model = withRandomState(MLXRandom.RandomState(seed: 7)) { Laguna(config) }
        if !moe {
            let weights = try MLX.loadArrays(
                url: fixture().appendingPathComponent("target.safetensors"))
            try model.update(
                parameters: .unflattened(model.sanitize(weights: weights)), verify: .all)
        }
        eval(model)
        return model
    }
    private func draft() throws -> LagunaDFlashModel {
        let config = try LagunaDFlashConfiguration(data: data("config"))
        let model = withRandomState(MLXRandom.RandomState(seed: 11)) { LagunaDFlashModel(config) }
        let weights = try MLX.loadArrays(
            url: fixture().appendingPathComponent("weights.safetensors"))
        try model.update(parameters: .unflattened(model.sanitize(weights: weights)), verify: .all)
        eval(model)
        return model
    }
    private func drain(_ iterator: any GenerationTokenIterator) -> [Int] {
        var result: [Int] = []
        while let token = iterator.next() { result.append(token) }
        XCTAssertNil(iterator.failure)
        return result
    }
    private func forward(_ model: Laguna, _ tokens: [Int], _ cache: [KVCache], verify: Bool) throws
        -> DFlashTargetOutput
    {
        try model.draftForward(
            MLXArray(tokens)[.newAxis], cache: cache, capture: [0, 2], verify: verify)
    }

    // Generated by Scripts/generate-laguna-dflash-fixture.py from mlx-vlm 06ff63d6.
    func testPythonDraftLogitsAcrossContextRollover() throws {
        struct Round: Decodable {
            let length: Int
            let logits: [Float]
            let tokens: [Int]
            let offsets: [Int]
        }
        final class Recorder: LogitSampler {
            var logits: [MLXArray] = []
            func sample(logits: MLXArray) -> MLXArray {
                self.logits.append(logits)
                return argMax(logits)
            }
        }
        let expected = try JSONDecoder().decode([[Round]].self, from: data("expected"))
        let model = try target()
        let drafter = try draft()
        for rounds in expected {
            let cache = drafter.newCache()
            for (step, round) in rounds.enumerated() {
                let features =
                    sin(MLXArray(0 ..< (round.length * 32)).asType(.float32) + step)
                    .reshaped(1, round.length, 32) * 0.1
                let sampler = Recorder()
                let result = try drafter.propose(
                    seed: MLXArray([Int32(2)]), features: features,
                    count: 3, target: model, cache: cache, sampler: sampler)
                XCTAssertEqual(result.asArray(Int.self), round.tokens)
                XCTAssertEqual(cache.map(\.offset), round.offsets)
                XCTAssertLessThan(
                    abs(concatenated(sampler.logits) - MLXArray(round.logits)).max().item(
                        Float.self), 0.0001)
            }
        }
    }

    func testMetadataValidationAndTargetMatching() throws {
        let root = try JSONSerialization.jsonObject(with: data("config")) as! [String: Any]
        XCTAssertTrue(try isTargetBoundDraftConfiguration(data("config")))
        XCTAssertTrue(try LagunaDFlashConfiguration.matches(data("config")))
        XCTAssertFalse(try LagunaDFlashConfiguration.matches(data("target-config")))
        let config = try LagunaDFlashConfiguration(data: data("config"))
        XCTAssertEqual(config.defaultProposalCount, 3)
        try config.validate(target: target())
        for (key, value): (String, Any) in [
            ("gating", "per-channel"), ("layer_types", ["sliding_attention"]),
            ("num_key_value_heads", 0), ("head_dim", 3), ("hidden_size", true),
            ("draft_vocab_size", 31), ("sliding_window", 1), ("sliding_windows", [8, 4]),
            ("eagle_aux_hidden_state_layer_ids", [0, 2]), ("qkv_bias", true),
            ("num_attention_heads_per_layer", [2]),
            ("rope_parameters", ["rope_type": "unknown"]),
        ] {
            var bad = root
            bad[key] = value
            XCTAssertThrowsError(
                try LagunaDFlashConfiguration(data: JSONSerialization.data(withJSONObject: bad)),
                key)
        }
        for (key, value): (String, Any) in [
            ("causal", false), ("causal", 1), ("block_size", 1), ("mask_token_id", 32),
            ("target_layer_ids", [2, 0]), ("target_layer_ids", [0, 4]),
            ("num_target_layers", 0),
        ] {
            var bad = root
            var inner = root["dflash_config"] as! [String: Any]
            inner[key] = value
            bad["dflash_config"] = inner
            XCTAssertThrowsError(
                try LagunaDFlashConfiguration(data: JSONSerialization.data(withJSONObject: bad)),
                key)
        }
        var mismatch = root
        var inner = root["dflash_config"] as! [String: Any]
        inner["num_target_layers"] = 5
        mismatch["dflash_config"] = inner
        let other = try LagunaDFlashConfiguration(
            data: JSONSerialization.data(withJSONObject: mismatch))
        XCTAssertThrowsError(try other.validate(target: target()))
    }

    func testSplitAndPrefixedWeightLoadingAndMissingWeights() throws {
        let model = try draft()
        let weights = Dictionary(uniqueKeysWithValues: model.parameters().flattened())
        var split = weights
        for index in 0 ..< 2 {
            let prefix = "layers.\(index).self_attn."
            let qkv = split.removeValue(forKey: prefix + "qkv_proj.weight")!
            split[prefix + "q_proj.weight"] = qkv[..<16]
            split[prefix + "k_proj.weight"] = qkv[16 ..< 24]
            split[prefix + "v_proj.weight"] = qkv[24...]
        }
        let prefixed = Dictionary(uniqueKeysWithValues: split.map { ("model." + $0.key, $0.value) })
        let sanitized = model.sanitize(weights: prefixed)
        try model.update(parameters: .unflattened(sanitized), verify: .all)
        for (key, expected) in weights {
            XCTAssertEqual(sanitized[key]?.asArray(Float.self), expected.asArray(Float.self))
        }
        for key in ["aux_hidden_norms.0.weight", "layers.0.self_attn.g_proj.weight"] {
            var missing = weights
            missing[key] = nil
            XCTAssertThrowsError(
                try model.update(
                    parameters: .unflattened(model.sanitize(weights: missing)), verify: .all))
        }
        var collision = weights
        collision["model.fc.weight"] = weights["fc.weight"]
        XCTAssertThrowsError(
            try model.update(
                parameters: .unflattened(model.sanitize(weights: collision)), verify: .all))
        split["layers.0.self_attn.k_proj.weight"] = nil
        XCTAssertThrowsError(
            try model.update(parameters: .unflattened(model.sanitize(weights: split)), verify: .all)
        )
    }

    func testRollbackPreservesDenseAndMoESlidingWindows() throws {
        for moe in [false, true] {
            let model = try target(moe: moe)
            for prefix in [0, 6, 8, 13] {
                for retained in [0, 1, 3, 4] {
                    let caches = try model.newCache(configuration: nil)
                    let fresh = try model.newCache(configuration: nil)
                    for cache in [caches, fresh] where prefix > 0 {
                        eval(try forward(model, Array(1 ... prefix), cache, verify: false).logits)
                    }
                    let output = try forward(model, [20, 21, 22, 23], caches, verify: true)
                    eval(output.logits, output.features)
                    XCTAssertEqual(output.features.shape, [1, 4, 32])
                    try output.commit?(retained)
                    if retained > 0 {
                        eval(
                            try forward(
                                model, Array([20, 21, 22, 23].prefix(retained)), fresh,
                                verify: false
                            ).logits)
                    }
                    XCTAssertEqual(caches.map(\.offset), fresh.map(\.offset))
                    let actual = try forward(model, [24], caches, verify: false).logits
                    let expected = try forward(model, [24], fresh, verify: false).logits
                    // Block and singleton SDPA have different reduction numerics.
                    XCTAssertLessThan(
                        abs(actual - expected).max().item(Float.self), 0.003,
                        "moe=\(moe), prefix=\(prefix), retained=\(retained)")
                }
            }
        }
    }

    func testAbandonedVerificationRestoresCaches() throws {
        let model = try target()
        let cache = try model.newCache(configuration: nil)
        eval(try forward(model, Array(1 ... 13), cache, verify: false).logits)
        let original = cache.map { $0.copy() }
        var output: DFlashTargetOutput? = try forward(model, [20, 21, 22, 23], cache, verify: true)
        eval(output!.logits)
        XCTAssertThrowsError(try output!.commit?(5))
        output = nil
        XCTAssertEqual(cache.map(\.offset), original.map(\.offset))
        for (a, b) in zip(cache, original) {
            XCTAssertEqual(
                a.state.map { $0.asArray(Float.self) }, b.state.map { $0.asArray(Float.self) })
        }
    }

    func testGenerationSamplingOutputLimitsAndReuse() throws {
        let model = try target(moe: true)
        let drafter = try draft()
        for temperature: Float in [0, 0.7] {
            for limit in [0, 1, 2, 7, 19] {
                let options = ModelGenerationOptions(
                    prefill: .init(stepSize: 4),
                    sampling: .init(temperature: temperature, topP: 0.9, seed: 42),
                    output: .init(maxTokens: limit))
                let input = LMInput(tokens: MLXArray(Array(1 ... 13)))
                let expected = drain(
                    try AutoregressiveIterator(input: input, model: model, options: options))
                let vault = DraftCacheVault()
                let iterator = try DFlashIterator(
                    input: input, target: model, draft: drafter,
                    options: options, speculation: .init(), checkpoint: { vault.latest = $0 })
                XCTAssertEqual(drain(iterator), expected)
                XCTAssertEqual(iterator.statistics.strategy, .dflash)
                let saved = try XCTUnwrap(vault.latest)
                let warm = try DFlashIterator(
                    input: LMInput(tokens: MLXArray([8, 9])), target: model,
                    draft: drafter, options: options, speculation: .init(), reuse: saved)
                let cold = try DFlashIterator(
                    input: LMInput(tokens: MLXArray(saved.tokens + [8, 9])),
                    target: model, draft: drafter, options: options, speculation: .init())
                XCTAssertEqual(drain(warm), drain(cold))
            }
        }
    }

    func testAllAcceptedRounds() throws {
        let model = try target()
        let drafter = try draft()
        model.update(parameters: model.parameters().mapValues { MLXArray.zeros(like: $0) })
        drafter.update(parameters: drafter.parameters().mapValues { MLXArray.zeros(like: $0) })
        let options = ModelGenerationOptions(
            sampling: .init(temperature: 0), output: .init(maxTokens: 19))
        let iterator = try DFlashIterator(
            input: LMInput(tokens: MLXArray([1, 2, 3])), target: model,
            draft: drafter, options: options, speculation: .init())
        XCTAssertEqual(drain(iterator), Array(repeating: 0, count: 19))
        XCTAssertGreaterThan(iterator.statistics.acceptedTokenCount, 0)
        XCTAssertEqual(
            iterator.statistics.acceptedTokenCount, iterator.statistics.proposedTokenCount)
    }

}
